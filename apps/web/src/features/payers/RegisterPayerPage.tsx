import { zodResolver } from '@hookform/resolvers/zod';
import { Alert, Button, Card, Group, Select, Stack, Text, TextInput } from '@mantine/core';
import { useNavigate } from '@tanstack/react-router';
import { type ReactElement, useState } from 'react';
import { Controller, useForm } from 'react-hook-form';

import { PayerType } from '@ircub/shared';

import { createPayer } from '../../api/payers.api';
import { ROUTES } from '../../app/routes.constants';
import { PageHeader } from '../../components/PageHeader';
import { notifyError, notifySuccess } from '../../lib/notify';

import { type PayerForm, payerSchema } from './payer.schema';

import type { RegisteredPayer } from '../../api/types';

export function RegisterPayerPage(): ReactElement {
  const navigate = useNavigate();
  const [registered, setRegistered] = useState<RegisteredPayer | null>(null);
  const form = useForm<PayerForm>({
    resolver: zodResolver(payerSchema),
    defaultValues: { type: PayerType.INDIVIDUAL, name: '', phone: '' },
  });
  const type = form.watch('type');

  const onSubmit = form.handleSubmit(async (values) => {
    try {
      const result = await createPayer({
        type: values.type,
        name: values.name,
        phone: values.phone,
        ...(values.email ? { email: values.email } : {}),
        ...(values.nationalId ? { nationalId: values.nationalId } : {}),
        ...(values.registrationNo ? { registrationNo: values.registrationNo } : {}),
        ...(values.address ? { address: values.address } : {}),
      });
      setRegistered(result);
      notifySuccess(`Registered ${result.name} as ${result.tin}`);
    } catch (caught: unknown) {
      notifyError(caught);
    }
  });

  if (registered !== null) {
    return (
      <Stack maw={640}>
        <PageHeader title="Payer registered" />
        <Card withBorder>
          <Stack>
            <Text>
              <strong>{registered.name}</strong> — TIN <code>{registered.tin}</code>, phone{' '}
              {registered.phone}
            </Text>
            {registered.warnings.length > 0 ? (
              <Alert
                color="orange"
                title={`${registered.warnings.length} possible duplicate(s) flagged for review`}
              >
                {registered.warnings.map((w) => (
                  <Text key={w.id} size="sm">
                    Same {w.matchField.toLowerCase().replace('_', ' ')} as{' '}
                    <strong>{w.matchedPayer.name}</strong> ({w.matchedPayer.tin})
                  </Text>
                ))}
              </Alert>
            ) : (
              <Alert color="teal">No duplicates detected.</Alert>
            )}
            <Group>
              <Button
                onClick={() =>
                  void navigate({ to: ROUTES.PAYER_DETAIL, params: { payerId: registered.id } })
                }
              >
                Open profile
              </Button>
              <Button
                variant="light"
                onClick={() => {
                  setRegistered(null);
                  form.reset();
                }}
              >
                Register another
              </Button>
            </Group>
          </Stack>
        </Card>
      </Stack>
    );
  }

  return (
    <Stack maw={640}>
      <PageHeader title="Register payer" />
      <Card withBorder>
        <form onSubmit={(event) => void onSubmit(event)}>
          <Stack>
            <Controller
              control={form.control}
              name="type"
              render={({ field }) => (
                <Select
                  label="Type"
                  data={Object.values(PayerType)}
                  value={field.value}
                  onChange={(v) => {
                    field.onChange(v ?? PayerType.INDIVIDUAL);
                  }}
                />
              )}
            />
            <TextInput
              label={type === PayerType.BUSINESS ? 'Business name' : 'Full name'}
              {...form.register('name')}
              error={form.formState.errors.name?.message}
            />
            <TextInput
              label="Phone"
              placeholder="+252 61 234 5678 or 061 234 5678"
              {...form.register('phone')}
              error={form.formState.errors.phone?.message}
            />
            <TextInput label="Email" {...form.register('email')} />
            {type === PayerType.BUSINESS ? (
              <TextInput label="Registration number" {...form.register('registrationNo')} />
            ) : (
              <TextInput label="National ID" {...form.register('nationalId')} />
            )}
            <TextInput label="Address" {...form.register('address')} />
            <Text size="xs" c="dimmed">
              The TIN is generated by the system. Matching phone, email or national ID raises a
              duplicate flag for supervisor review; registration is not blocked.
            </Text>
            <Button type="submit" loading={form.formState.isSubmitting}>
              Register
            </Button>
          </Stack>
        </form>
      </Card>
    </Stack>
  );
}
